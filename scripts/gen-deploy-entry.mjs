#!/usr/bin/env node
// Derive deploy/opencode-plugin/project-memory.ts from src/index.ts.
//
// The production deployment form is multi-file TS loaded directly by opencode,
// so it cannot use the npm package's single-file bundle. Its entry therefore
// duplicates src/index.ts with two mechanical differences: shared-module import
// paths gain a ./project-memory/src/ prefix, and the inlined WRITER_PROMPT
// constant is replaced by a runtime read of writer-prompt.txt.
//
// It used to be maintained by hand, and drifted twice in one session — most
// seriously by omitting maxWriterRetries, which made `failures >= undefined`
// permanently false and disabled the retry cap in production with no error.
// Generating it removes the failure mode; --check makes drift a release-gate
// failure like the prompt module.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SRC_ENTRY = path.join(repoRoot, "src", "index.ts")
const DEPLOY_ROOT = path.join(repoRoot, "deploy", "opencode-plugin")
const DEPLOY_ENTRY = path.join(DEPLOY_ROOT, "project-memory.ts")
const DEPLOY_SRC = path.join(DEPLOY_ROOT, "project-memory", "src")

const IMPORT_PREFIX = "./project-memory/src/"
const PROMPT_READ =
  'fs.readFileSync(path.join(import.meta.dir, "project-memory", "src", "session", "writer-prompt.txt"), "utf8")'

const HEADER = [
  "// AUTO-GENERATED from src/index.ts by scripts/gen-deploy-entry.mjs",
  "// Do not edit this file — edit src/index.ts and re-run `npm run gen:deploy-entry`.",
  "// Two mechanical differences from src/index.ts: shared-module import paths",
  "// carry the ./project-memory/src/ prefix, and WRITER_PROMPT is read at runtime",
  "// so the production form reads writer-prompt.txt (the single prompt source)",
  "// instead of the inlined constant the npm bundle uses.",
  "",
].join("\n")

export function renderDeployEntry(source) {
  const lines = source.replace(/\r\n/g, "\n").split("\n")
  const out = []
  const rewritten = []
  for (const line of lines) {
    // The prompt constant only exists in the bundle; the deploy form reads the
    // .txt at runtime, so the import is dropped along with it.
    if (/^import \{ WRITER_PROMPT \} from "\.\/session\/prompt\.ts"$/.test(line)) continue
    // Matches both `import { x } from "./y.ts"` and the closing line of a
    // multi-line import, `} from "./y.ts"`. The `from "` must not be preceded by
    // a quote so a URL or message string cannot be mistaken for a specifier.
    const m = /^([^'"]*?\bfrom\s+)"\.(\/[^"]+)"(.*)$/.exec(line)
    if (m) {
      const target = m[2]
      rewritten.push(target.replace(/^\//, ""))
      out.push(`${m[1]}"${IMPORT_PREFIX}${target.replace(/^\//, "")}"${m[3]}`)
      continue
    }
    if (line.includes("writerPrompt: WRITER_PROMPT,")) {
      out.push(line.replace("WRITER_PROMPT", PROMPT_READ))
      continue
    }
    out.push(line)
  }
  return { text: HEADER + out.join("\n"), rewritten }
}

const check = process.argv.includes("--check")
const source = fs.readFileSync(SRC_ENTRY, "utf8")
const { text, rewritten } = renderDeployEntry(source)

// Safety net: every rewritten import must resolve inside the deploy tree. A new
// shared module added to src/index.ts but not yet synced would otherwise produce
// an entry that fails to load only at runtime in production.
const shared = fs.readFileSync(path.join(repoRoot, "scripts", "sync-deploy.mjs"), "utf8")
const missing = rewritten.filter((rel) => !fs.existsSync(path.join(DEPLOY_SRC, rel)))
if (missing.length > 0) {
  console.error(`✗ 入口引用了未同步到 deploy 的模块(${missing.length} 个):`)
  for (const rel of missing) {
    // Two distinct causes, and telling them apart saves a confusing detour:
    // either the module was never declared as shared, or it was declared and
    // sync:deploy simply has not been run since.
    const declared = shared.includes(`"${rel}"`)
    console.error(`    ${rel}  ← ${declared ? "已在 SHARED_REL 中,先运行 npm run sync:deploy" : "需加入 scripts/sync-deploy.mjs 的 SHARED_REL"}`)
  }
  process.exit(1)
}

const current = fs.existsSync(DEPLOY_ENTRY) ? fs.readFileSync(DEPLOY_ENTRY, "utf8") : null
if (check) {
  if (current !== text) {
    console.error("deploy 入口与 src/index.ts 不一致。运行: npm run gen:deploy-entry")
    process.exit(1)
  }
  console.log(`deploy 入口与 src/index.ts 一致(${rewritten.length} 个导入路径)`)
} else {
  fs.writeFileSync(DEPLOY_ENTRY, text, "utf8")
  const same = current === text
  console.log(
    same
      ? `已生成 deploy 入口,无变化(${rewritten.length} 个导入路径)`
      : `已生成 deploy 入口(${rewritten.length} 个导入路径)`,
  )
}
